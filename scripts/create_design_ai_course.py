def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(text).strip() + "\n", encoding="utf-8")


def write_raw(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def write_csv(path: Path, rows: list[list[str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerows(rows)


def md_table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join(["---"] * len(headers)) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(cell.replace("\n", "<br>") for cell in row) + " |")
    return "\n".join(lines)


def slide(
    no: int,
    title: str,
    headline: str,
    blocks: list[tuple[str, str]],
    pattern: str,
    screenshot: str = "なし",
) -> str:
    lines = [f"### S{no:02d} {title}", f"**ヘッドライン:** {headline}", ""]
    for idx, (label, body) in enumerate(blocks, start=1):
        lines.append(f"**内容ブロック{idx}：{label}**")
        lines.append(body.strip())
        lines.append("")
    lines.extend(
        [
            f"- **図解パターン:** {pattern}",
            f"- **テンプレートID:** {TEMPLATE_ID}",
            f"- **スクリーンショット:** {screenshot}",
            "",
            "---",
            "",
        ]
    )
    return "\n".join(lines)


