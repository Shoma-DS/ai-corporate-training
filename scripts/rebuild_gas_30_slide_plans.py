"""Rewrite GAS course sessions 3-6 into 30-slide full-raster slide plans.

This script updates source markdown only. It does not draw, rasterize, or
generate slide images.
"""

from __future__ import annotations

from pathlib import Path


COURSE_DIR = Path("講座/生成AI・GASで実践する業務変革・DX推進講座")
COURSE_TITLE = "生成AI・GASで実践する業務変革・DX推進講座"
TEMPLATE = "isometric-corporate-clean"
WIREFRAME = "skills/corporate-training-course-builder/references/assets/講座スライドレイアウトワイヤフレーム.png"


def slide(
    no: int,
    title: str,
    headline: str,
    blocks: list[tuple[str, str]],
    pattern: str,
    screenshot: str = "なし",
) -> str:
    lines = [
        f"### S{no:02d} {title}",
        f"**ヘッドライン:** {headline}",
        "",
    ]
    for idx, (label, body) in enumerate(blocks, start=1):
        lines.append(f"**内容ブロック{idx}：{label}**")
        lines.append(body.strip())
        lines.append("")
    lines.extend(
        [
            f"- **図解パターン:** {pattern}",
            f"- **テンプレートID:** {TEMPLATE}",
            f"- **スクリーンショット:** {screenshot}",
            "",
            "---",
            "",
        ]
    )
    return "\n".join(lines)


def divider(no: int, idx: int, total: int, name: str, minutes: str, rail: str, exit_line: str) -> str:
    return slide(
        no,
        f"章見出し/現在位置 {idx}/{total}: {name}",
        f"ここから「{idx}. {name}」に入ります",
        [
            ("現在位置（特大表示）", f"- **{idx}. {name}**（{minutes}）"),
            ("章レール", f"- {rail}"),
            ("この章の出口", f"- {exit_line}"),
        ],
        "chapter-divider-hero（章見出し/現在位置・特大表示）",
    )


def render_plan(
    session_no: int,
    session_title: str,
    intro: str,
    strip_rows: list[tuple[int, str]],
    allocations: list[tuple[str, str, str, str]],
    policy: list[str],
    slides: list[str],
) -> str:
    strip = "\n".join(f"| {no} | {name} |" for no, name in strip_rows)
    allocation = "\n".join(f"| {name} | {minutes} | {ranges} | {goal} |" for name, minutes, ranges, goal in allocations)
    policy_text = "\n".join(f"- {item}" for item in policy)
    body = "\n".join(slides).rstrip()
    return f"""# 第{session_no}回 スライド構成案: {session_title}

対象講座: {COURSE_TITLE}
スライド枚数: 30枚 / 120分（2026-07-09改訂・旧40枚超構成から統合）
テンプレートID: {TEMPLATE}（全スライド共通）
レイアウト標準: 1枚まるごとラスター画像＋固定レイアウトワイヤーフレーム参照（`{WIREFRAME}`）

---

## 設計方針

{policy_text}
- 旧40枚超構成の重複説明、章見出しの詳細表、デモ前後の反復、演習の再説明を統合し、情報量を落とさず30枚に圧縮する。
- 章見出し/現在位置スライドは第1回と同じく、現在章の番号・章名を特大で見せるヒーロー型にする。詳細な論点は次の通常スライドで扱う。
- 生成画像は `imagegen` / Codex App Server / GPT image 2 で1枚まるごとの完成ラスター画像として作る。SVG、HTML/CSS、canvas、PIL、後載せ文字は使わない。
- 録画動画形式のため「今から○分取ります」は使わず「動画を一時停止して〜分ほど取り組んでください」を使う。

{intro}

---

## 目次ストリップ表示名

| 章 | 表示名 |
|---:|---|
{strip}

---

## 120分の時間配分

| ブロック | 時間 | スライド範囲 | ねらい |
|---|---:|---|---|
{allocation}

---

## スライド詳細

---

{body}
"""


